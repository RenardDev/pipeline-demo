"""Render explicit GitHub graph nodes from the shared demo topology."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "demo" / "pipeline.json"
WORKFLOW = ROOT / ".github" / "workflows" / "pipeline-demo.yml"
CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7"
UPLOAD = "actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9 # v7"
DOWNLOAD = "actions/download-artifact@37930b1c2abaa49bbe596cd826c3c89aef350131 # v7"


def load_nodes():
    nodes = json.loads(CONFIG.read_text(encoding="utf-8"))["nodes"]
    seen = set()
    for node in nodes:
        if node["id"] in seen or any(dep not in seen for dep in node["needs"]):
            raise ValueError(f"Duplicate, unknown or non-topological node: {node['id']}")
        seen.add(node["id"])
        if len(node["tasks"]) != 3 or not 0 < node["offset"] <= 300:
            raise ValueError(f"Invalid tasks or deadline: {node['id']}")
        if any(next(n for n in nodes if n["id"] == dep)["offset"] > node["offset"] for dep in node["needs"]):
            raise ValueError(f"Deadline precedes dependency: {node['id']}")
    if set(nodes[-1]["needs"]) != seen - {"report"}:
        raise ValueError("The final report must observe every other job")
    return nodes


def render():
    lines = [
        "# Generated by scripts/generate_workflow.py; edit demo/pipeline.json, then regenerate.",
        "name: Pipeline Observatory · 5 minute demo",
        "run-name: \"🎬 Demo #${{ github.run_number }} · ${{ inputs.duration_seconds || 300 }}s · failure=${{ inputs.fail_at || 'none' }}\"",
        "", "on:", "  workflow_dispatch:", "    inputs:",
        "      duration_seconds:", "        description: 'Target duration (runner queues may extend the total runtime)'",
        "        type: choice", "        required: true", "        default: '300'", "        options: ['300', '120', '30']",
        "      fail_at:", "        description: 'Inject a demo failure (none for a successful run)'",
        "        type: choice", "        required: true", "        default: none",
        "        options: [none, unit_api, security_gate, e2e_chromium, canary]",
        "  push:", "    branches: [main]", "  pull_request:", "    branches: [main]", "",
        "permissions:", "  contents: read", "",
        "concurrency:", "  group: pipeline-demo-${{ github.workflow }}-${{ github.ref }}", "  cancel-in-progress: true", "",
        "defaults:", "  run:", "    shell: bash", "",
        "env:", "  PYTHONUNBUFFERED: '1'", "  PYTHONUTF8: '1'",
        "  DEMO_DURATION: ${{ inputs.duration_seconds || '300' }}",
        "  DEMO_FAILURE: ${{ inputs.fail_at || 'none' }}", "", "jobs:",
    ]
    for node in load_nodes():
        node_id = node["id"]
        lines.extend([f"  {node_id}:", f"    name: '{node['name']}'"])
        if node["needs"]:
            lines.append(f"    needs: [{', '.join(node['needs'])}]")
        if node_id == "rollback":
            lines.append("    if: ${{ !cancelled() && needs.canary.result == 'failure' }}")
        elif node_id in {"cleanup", "report"}:
            lines.append("    if: ${{ !cancelled() }}")
        lines.extend(["    runs-on: ubuntu-latest", "    timeout-minutes: 8"])
        if node_id != "report":
            output = "steps.clock.outputs.started_at" if node_id == "plan" else "steps.demo.outputs.started_at"
            lines.extend(["    outputs:", f"      started_at: ${{{{ {output} }}}}"])
        lines.append("    steps:")
        if node_id == "plan":
            lines.extend([
                "      - name: 'Start the shared demo clock'", "        id: clock", "        run: |",
                '          python3 - <<\'PY\'', "          import os, time",
                '          with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as output:',
                '              output.write(f"started_at={time.time()}\\n")', "          PY",
            ])
        lines.extend([f"      - uses: {CHECKOUT}", "        with:", "          persist-credentials: false"])
        if node_id == "plan":
            lines.extend([
                "      - name: 'Validate topology and failure-handling scenarios'",
                "        run: |",
                "          python3 scripts/generate_workflow.py --check",
                "          python3 -m unittest discover -s tests -v",
            ])
        if node_id == "report":
            lines.extend([
                "      - name: 'Gather all available process artifacts'", f"        uses: {DOWNLOAD}",
                "        with:", "          pattern: process-*",
                "          path: reports", "          merge-multiple: false",
                "      - name: 'Build mission control dashboard & workflow summary'", "        if: ${{ !cancelled() }}",
                "        env:", "          DEMO_STARTED_AT: ${{ needs.plan.outputs.started_at }}",
                "          DEMO_NEEDS_JSON: ${{ toJSON(needs) }}", "        run: python3 scripts/demo_pipeline.py report",
                "      - name: 'Publish graph, timeline and full evidence'", "        if: ${{ !cancelled() }}",
                f"        uses: {UPLOAD}", "        with:",
                "          name: mission-control-${{ github.run_id }}-${{ github.run_attempt }}",
                "          path: reports/", "          if-no-files-found: error", "          retention-days: 7",
                "          compression-level: 1",
            ])
        else:
            if node_id == "plan":
                clock = "steps.clock.outputs.started_at"
            else:
                clock = " || ".join(f"needs.{dep}.outputs.started_at" for dep in node["needs"])
            lines.extend([
                "      - name: 'Run the three process phases'", "        id: demo",
                "        uses: ./.github/actions/demo-stage", "        with:", f"          node: {node_id}",
                f"          started-at: ${{{{ {clock} }}}}",
            ])
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated YAML is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not WORKFLOW.exists() or WORKFLOW.read_text(encoding="utf-8") != content:
            parser.exit(1, "Workflow is stale; run python scripts/generate_workflow.py\n")
        print("Workflow matches the validated 32-node topology.")
    else:
        WORKFLOW.parent.mkdir(parents=True, exist_ok=True)
        WORKFLOW.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated {WORKFLOW.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
